  function forPoint(p) {
    var tips = [];
    if (p.hint) tips.push(p.hint);
    if (POINT_HINTS[p.id]) tips.push(POINT_HINTS[p.id]);
    var key = p.title + " " + (p.tag || "");
    (RULES[p.subject] || []).forEach(function (r) {
      if (tips.length >= 3) return;
      if (r.re.test(key)) {
        r.tips.forEach(function (t) { if (tips.length < 3 && tips.indexOf(t) < 0) tips.push(t); });
      }
    });
    (FALLBACK[p.subject] || []).forEach(function (t) {
      if (tips.length < 2 && tips.indexOf(t) < 0) tips.push(t);
    });
    var bullets = bulletsOf(p).slice(0, 3);
    return { tips: tips.slice(0, 3), bullets: bullets };
  }

