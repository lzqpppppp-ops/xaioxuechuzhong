  function bulletsOf(p) {
    var lines = String(p.explain || "").split("\n").map(function (s) { return s.trim(); }).filter(Boolean);
    return lines.filter(function (l) { return /^[-·•]\s+/.test(l); }).map(function (l) { return l.replace(/^[-·•]\s+/, ""); });
  }

